using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Input;
using Microsoft.UI.Xaml.Media;

namespace DockingScene.Controls;

public sealed partial class StandardSwitcher
{
    /// <summary>True only when this overlay, rather than its launch editor, owns focus.</summary>
    public bool HasInputFocus
    {
        get
        {
            if (XamlRoot is not { } root) return false;
            for (var node = FocusManager.GetFocusedElement(root) as DependencyObject;
                 node is not null; node = VisualTreeHelper.GetParent(node))
                if (ReferenceEquals(node, this)) return true;
            return false;
        }
    }

    internal void TakeInputFocus()
    {
        if (_completed || XamlRoot is null || HasInputFocus) return;
        // Opening from an accelerator can be followed immediately by a character.
        // Do not wait for Loaded or the next dispatcher tick to move focus.
        ApplyTemplate();
        if (!Focus(FocusState.Programmatic))
        {
            UpdateLayout();
            if (!Focus(FocusState.Programmatic))
                (SelectedId is { } id && _layout.Windows[id].Kind == Core.WindowKind.Tool ? _tools : _documents)
                    .Focus(FocusState.Programmatic);
        }
    }

    protected override void OnCharacterReceived(CharacterReceivedRoutedEventArgs e)
    {
        // Text generated by the modal confirmation key is not document input.
        e.Handled = true;
    }
}
